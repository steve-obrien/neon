    updateFieldProps: function updateFieldProps(state, payload) {
      var field = payload.field;

      var index = _.findIndex(state.form.fields, function (f) {
        return f.name == field.name;
      }); // TODO: remove the need for this bull


      if (_.isDefined(payload.update.required) && field.required !== payload.update.required) {
        if (payload.update.required === false) {
          reqValidatorKey = _.findKey(field.validators, function (validator) {
            return validator.class === "neon\\core\\validators\\RequiredValidator";
          });
          Vue.delete(field.validators, reqValidatorKey);
        } else {
          Vue.set(field.validators, 'required', {
            "class": "neon\\core\\validators\\RequiredValidator"
          });
        }
      }

      var field = _.extend({}, field, payload.update);

      state.form.fields.splice(index, 1, field);
    },

