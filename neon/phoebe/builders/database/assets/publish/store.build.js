    addField: function addField(state, payload) {
      // look up the default object for the type
      var componentRef = payload.fieldType.toLowerCase();
      var defaultComponentState = FormBuilderApp.getDefaultState(componentRef);

      if (_.isUndefined(defaultComponentState)) {
        throw 'No default state object found in FormBuilderApp.widgets.defaultStates for widget of type : "' + componentRef + '"';
      }

      var fieldData = JSON.parse(JSON.stringify(defaultComponentState)); // generate a unique name for the field

      fieldData.name = FormBuilderApp.helpers.makeUniqueName(fieldData.name); // emulate the id auto generation - we should remove this from the state via a getter.
      // so it is NOT passed when saving.
      // we do not want to store the id - the id should always be auto generated by the server from the form name and the field name

      fieldData.order = payload.at; // find the form

      var form = {};

      if (state.form == payload.form) {
        form = state.form;
      } else {
        form = _.find(state.form.fields, function (field) {
          return field.name == payload.form.name;
        });
      }

      form.fields.splice(payload.at, 0, fieldData);
      neon.Store.commit('phoebe/setEditingField', {
        field: fieldData
      });
    },

